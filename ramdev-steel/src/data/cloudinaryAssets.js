export function migrateLegacyImageReferences(value) {
  if (typeof value === "string") {
    if (
      value.startsWith(
        "https://images.unsplash.com/photo-1504917595217-d4dc5ebe6122",
      )
    ) {
      return cloudinaryAssets["remote/hero"];
    }
    if (
      value.startsWith(
        "https://images.unsplash.com/photo-1531058020387-3be344556be6",
      )
    ) {
      return cloudinaryAssets["remote/about"];
    }

    const assetPrefix = "/src/assets/";
    if (!value.startsWith(assetPrefix)) return value;
    const assetPath = value.slice(assetPrefix.length);
    return cloudinaryAssets[assetPath] || value;
  }

  if (Array.isArray(value)) {
    return value.map(migrateLegacyImageReferences);
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, nestedValue]) => [
        key,
        migrateLegacyImageReferences(nestedValue),
      ]),
    );
  }

  return value;
}
